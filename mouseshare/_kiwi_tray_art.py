_DATA = {"slim14": _SLIM14, "slim22": _SLIM22}


@lru_cache(maxsize=4)
def master_png(variant=None):
    """Return the 512x512 RGBA master mask PNG bytes for *variant*.

    tray_icon() requests four sizes; decoding the 15 KB blob once per process
    avoids repeating the base64 work on every QIcon build.
    """
    key = variant or DEFAULT_VARIANT
    if key not in _DATA:
        raise KeyError(f"unknown tray artwork variant: {key}")
    return base64.b64decode(_DATA[key])
