@lru_cache(maxsize=8)
def size_png(size):
    """Return the finished PNG bytes for an exact tray *size*, or None.

    These are the user's per-size renders and are used verbatim — no rescale,
    no alpha hardening. Callers that get None should fall back to master_png().
    """
    blob = _SIZED.get(size)
    return base64.b64decode(blob) if blob is not None else None


